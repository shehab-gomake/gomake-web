import { useEffect, useState } from "react";
import Head from "next/head";
import { useRecoilValue } from "recoil";
import { companyProfileState } from "@/store/company-profile";
import { useRouter } from "next/router";

/**
 * DynamicMetaTags Component
 * 
 * Sets Open Graph meta tags for social media link previews (WhatsApp, Facebook, etc.)
 * Uses the Login Logo from company profile as the preview image
 */
export const DynamicMetaTags = () => {
  const router = useRouter();
  const companyProfile = useRecoilValue(companyProfileState);
  const [loginLogo, setLoginLogo] = useState<string | null>(null);
  const [companyName, setCompanyName] = useState<string>("Gomake");

  useEffect(() => {
    // Try to get login logo from Recoil state first
    if (companyProfile?.loginLogo) {
      setLoginLogo(companyProfile.loginLogo);
      if (companyProfile.name) {
        setCompanyName(companyProfile.name);
      }
      return;
    }

    // Fallback: Try to get from localStorage (set during login/validation)
    if (typeof window !== "undefined") {
      const storedLoginLogo = localStorage.getItem("loginLogo");
      const storedSystemLogo = localStorage.getItem("systemLogo");
      const storedCompanyName = localStorage.getItem("companyName");
      
      if (storedLoginLogo) {
        setLoginLogo(storedLoginLogo);
      } else if (storedSystemLogo) {
        // Fallback to system logo if login logo not available
        setLoginLogo(storedSystemLogo);
      }
      
      if (storedCompanyName) {
        setCompanyName(storedCompanyName);
      }
    }
  }, [companyProfile]);

  // Get current page URL
  const currentUrl =
    typeof window !== "undefined"
      ? `${window.location.origin}${router.asPath}`
      : "";

  // Helper function to ensure absolute URL (required by WhatsApp)
  const ensureAbsoluteUrl = (url: string | null): string => {
    if (!url) return "";
    // If already absolute URL (starts with http:// or https://)
    if (url.startsWith("http://") || url.startsWith("https://")) {
      return url;
    }
    // If relative URL, make it absolute
    if (typeof window !== "undefined") {
      return `${window.location.origin}${url.startsWith("/") ? url : `/${url}`}`;
    }
    return url;
  };

  // Default fallback image if no logo is available
  const defaultImage =
    "https://gomake-translations.s3.eu-central-1.amazonaws.com/favicon.ico";

  const ogImage = loginLogo ? ensureAbsoluteUrl(loginLogo) : defaultImage;
  const siteName = companyName || "Gomake";
  const pageTitle = `${siteName} - Business Management Platform`;

  return (
    <Head>
      {/* Open Graph / Facebook / WhatsApp */}
      <meta property="og:type" content="website" />
      <meta property="og:url" content={currentUrl} />
      <meta property="og:title" content={pageTitle} />
      <meta
        property="og:description"
        content="Generated by create next app"
      />
      <meta property="og:image" content={ogImage} />
      <meta property="og:image:width" content="1200" />
      <meta property="og:image:height" content="630" />
      <meta property="og:image:alt" content={`${siteName} Logo`} />
      <meta property="og:site_name" content={siteName} />

      {/* Twitter Card */}
      <meta name="twitter:card" content="summary_large_image" />
      <meta name="twitter:url" content={currentUrl} />
      <meta name="twitter:title" content={pageTitle} />
      <meta
        name="twitter:description"
        content="Generated by create next app"
      />
      <meta name="twitter:image" content={ogImage} />

      {/* Favicon - use login logo if available */}
      {loginLogo && (
        <link rel="icon" type="image/png" href={loginLogo} />
      )}
    </Head>
  );
};

