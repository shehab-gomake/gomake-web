/**
 * Add Group Modal
 * Modal for creating new template groups
 */

import React, { useState } from 'react';
import {
  Dialog,
  DialogTitle,
  DialogContent,
  DialogActions,
  Box,
  TextField,
  Typography,
  IconButton,
} from '@mui/material';
import { Close as CloseIcon } from '@mui/icons-material';
import { Button } from '@/widgets/frontdesk/design-system';
import { useRecoilState } from 'recoil';
import { settingsAddGroupModalAtom } from '@/store/frontdesk/atoms/settings.atoms';
import { useMessageTemplates } from '../../hooks/use-message-templates';

export const AddGroupModal: React.FC = () => {
  const { addTemplateGroup } = useMessageTemplates();
  const [open, setOpen] = useRecoilState(settingsAddGroupModalAtom);

  // Local state
  const [groupName, setGroupName] = useState('');
  const [groupDescription, setGroupDescription] = useState('');

  // Handle save
  const handleSave = async () => {
    if (!groupName.trim()) return;

    await addTemplateGroup({
      id: '', // Will be generated by backend
      name: groupName,
      description: groupDescription,
    });

    // Reset form
    setGroupName('');
    setGroupDescription('');
  };

  // Handle close
  const handleClose = () => {
    setOpen(false);
    setGroupName('');
    setGroupDescription('');
  };

  return (
    <Dialog open={open} onClose={handleClose} maxWidth="sm" fullWidth>
      <DialogTitle
        sx={{
          display: 'flex',
          justifyContent: 'space-between',
          alignItems: 'center',
          borderBottom: '1px solid',
          borderColor: 'divider',
          pb: 2,
        }}
      >
        <Typography variant="h6">Add New Template Group</Typography>
        <IconButton onClick={handleClose} size="small">
          <CloseIcon />
        </IconButton>
      </DialogTitle>

      <DialogContent sx={{ pt: 3 }}>
        <Box sx={{ display: 'flex', flexDirection: 'column', gap: 3 }}>
          <TextField
            label="Group Name"
            value={groupName}
            onChange={(e) => setGroupName(e.target.value)}
            fullWidth
            required
            placeholder="Enter group name..."
            helperText="Required: A unique name for this template group"
          />

          <TextField
            label="Description"
            value={groupDescription}
            onChange={(e) => setGroupDescription(e.target.value)}
            fullWidth
            multiline
            rows={4}
            placeholder="Enter description..."
            helperText="Optional: Describe the purpose of this group"
          />
        </Box>
      </DialogContent>

      <DialogActions
        sx={{
          borderTop: '1px solid',
          borderColor: 'divider',
          px: 3,
          py: 2,
          gap: 1,
        }}
      >
        <Button variant="secondary" onClick={handleClose}>
          Cancel
        </Button>
        <Button variant="primary" onClick={handleSave} disabled={!groupName.trim()}>
          Create Group
        </Button>
      </DialogActions>
    </Dialog>
  );
};
