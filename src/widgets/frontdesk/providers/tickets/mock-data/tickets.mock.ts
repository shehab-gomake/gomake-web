// Ticket view filters
export const ticketViews = {
  myTickets: (ticket: Ticket, currentUserId: string) =>
    ticket.assignedTo?.userId === currentUserId,

  pastDue: (ticket: Ticket) => {
    if (!ticket.dueDate) return false;
    return new Date(ticket.dueDate) < new Date() && ticket.status !== 'Done';
  },

  highPriority: (ticket: Ticket) =>
    ticket.priority === 'High' || ticket.priority === 'Urgent',

  unassigned: (ticket: Ticket) =>
    !ticket.assignedTo,

  allTickets: (_ticket: Ticket) => true,
};